package com.agentic.chatbot.stage.template;

import com.agentic.chatbot.stage.LanguageProfile;
import com.agentic.chatbot.stage.StageDomain;
import com.agentic.chatbot.stage.StageLanguage;
import com.agentic.chatbot.stage.StagePrompts;

import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Offline Developer and Tester output for JavaScript, TypeScript, C#, Go and Kotlin: the banking fund transfer
 * (when the requirement is a fund transfer) or the generic submit / approve / reject workflow named after the
 * feature, each with a unit-test suite in the language's standard framework. Other code gets a test skeleton.
 */
public final class PolyglotTemplates {

    /** Marks generated code so the Tester can recognise it offline. */
    public static final String MARKER = "Generated by BOT offline template";

    public static final List<StageLanguage> LANGUAGES = List.of(StageLanguage.JAVASCRIPT, StageLanguage.TYPESCRIPT,
            StageLanguage.CSHARP, StageLanguage.GO, StageLanguage.KOTLIN);

    private static final String FUND_NAME = "FundTransfer";
    private static final Pattern SERVICE = Pattern.compile("\\b(?:class|struct|type)\\s+(\\w+?)Service\\b");
    private static final Pattern GO_PACKAGE = Pattern.compile("(?m)^package\\s+(\\w+)");
    private static final Pattern KOTLIN_PACKAGE = Pattern.compile("(?m)^package\\s+([\\w.]+)");
    private static final Pattern TYPE_NAMES = Pattern.compile(
            "(?m)^\\s*(?:export\\s+)?(?:public\\s+|internal\\s+)?(?:sealed\\s+|static\\s+|data\\s+|abstract\\s+)*"
                    + "(?:class|interface|enum|record|struct|object)\\s+([A-Z]\\w*)|^\\s*(?:export\\s+)?(?:async\\s+)?function\\s+(\\w+)"
                    + "|^func\\s+(?:\\([^)]*\\)\\s*)?([A-Z]\\w*)|^\\s*fun\\s+(\\w+)");

    private PolyglotTemplates() {
    }

    public static boolean supports(StageLanguage language) {
        return LANGUAGES.contains(language);
    }

    /** True when the requirement asks for the banking fund-transfer sample rather than the generic workflow. */
    public static boolean fundTransfer(StageDomain domain, String input) {
        return StageSample.detect(input, domain) == StageSample.FUND_TRANSFER;
    }

    /** Source files (and a small entry point where the language needs one) for the requirement. */
    public static Map<String, String> code(StageLanguage language, StageDomain domain, String stories) {
        boolean fund = fundTransfer(domain, stories);
        String name = fund ? FUND_NAME : StageSample.detect(stories, domain).featureName(stories);
        String snake = StagePrompts.snake(name);
        String pkg = kotlinPackage(domain, stories);
        Map<String, String> files = new LinkedHashMap<>();
        switch (language) {
            case JAVASCRIPT -> files.put("src/" + snake + ".js", fill(fund ? JsTemplates.FUND : JsTemplates.WORKFLOW, domain, name, pkg));
            case TYPESCRIPT -> files.put("src/" + snake + ".ts", fill(fund ? TsTemplates.FUND : TsTemplates.WORKFLOW, domain, name, pkg));
            case CSHARP -> {
                files.put("src/App/" + name + "Service.cs", fill(fund ? CSharpTemplates.FUND : CSharpTemplates.WORKFLOW, domain, name, pkg));
                files.put("src/App/Program.cs", fill(fund ? CSharpTemplates.FUND_PROGRAM : CSharpTemplates.WORKFLOW_PROGRAM, domain, name, pkg));
            }
            case GO -> {
                files.put("app/" + snake + ".go", fill(fund ? GoTemplates.FUND : GoTemplates.WORKFLOW, domain, name, pkg));
                files.put("app/main.go", fill(fund ? GoTemplates.FUND_MAIN : GoTemplates.WORKFLOW_MAIN, domain, name, pkg));
            }
            case KOTLIN -> {
                String dir = "src/main/kotlin/" + pkg.replace('.', '/') + "/";
                files.put(dir + name + "Service.kt", fill(fund ? KotlinTemplates.FUND : KotlinTemplates.WORKFLOW, domain, name, pkg));
                files.put(dir + "Main.kt", fill(fund ? KotlinTemplates.FUND_MAIN : KotlinTemplates.WORKFLOW_MAIN, domain, name, pkg));
            }
            default -> throw new IllegalArgumentException("No offline template for " + language.label());
        }
        return files;
    }

    /**
     * Unit tests for the given sources: the full suite for code from these templates, otherwise one skeleton per
     * source file (marked "generated offline by BOT") that loads the code and lists what to test.
     */
    public static Map<String, String> tests(StageLanguage language, StageDomain domain, Map<String, String> sources) {
        Map<String, String> tests = new LinkedHashMap<>();
        for (Map.Entry<String, String> e : sources.entrySet()) {
            String path = e.getKey();
            String code = e.getValue();
            if (!path.endsWith("." + language.ext()) || isEntryOnly(language, path)) {
                continue;
            }
            Matcher service = SERVICE.matcher(code);
            if (code.contains(MARKER) && service.find()) {
                String name = service.group(1);
                boolean fund = code.toLowerCase(Locale.ROOT).replace("_", "").contains("dailylimit");
                tests.putAll(suite(language, domain, name, fund, path, code));
            } else {
                tests.putAll(skeleton(language, path, code));
            }
        }
        return tests;
    }

    /** Build files for the code ({@code withTests}: also the unit-test project where the language has one). */
    public static Map<String, String> scaffold(StageLanguage language, String app, boolean withTests) {
        Map<String, String> files = new LinkedHashMap<>(DeployTemplates.scaffold(LanguageProfile.of(language), app));
        if (language == StageLanguage.CSHARP && withTests) {
            files.put("tests/App.Tests/App.Tests.csproj", CSharpTemplates.TEST_CSPROJ);
        }
        return files;
    }

    static String csharpProject() {
        return CSharpTemplates.APP_CSPROJ;
    }

    static String kotlinBuild() {
        return KotlinTemplates.BUILD_GRADLE;
    }

    private static boolean isEntryOnly(StageLanguage language, String path) {
        String file = path.substring(path.lastIndexOf('/') + 1);
        return switch (language) {
            case CSHARP -> file.equals("Program.cs");
            case GO -> file.equals("main.go") || file.endsWith("_test.go");
            case KOTLIN -> file.equals("Main.kt");
            default -> false;
        };
    }

    private static Map<String, String> suite(StageLanguage language, StageDomain domain, String name, boolean fund,
                                             String path, String code) {
        String base = baseName(path);
        String pkg = matchOr(KOTLIN_PACKAGE, code, "app");
        return switch (language) {
            case JAVASCRIPT -> Map.of("tests/" + base + ".test.js", fill(fund ? JsTemplates.FUND_TEST : JsTemplates.WORKFLOW_TEST,
                    domain, name, pkg).replace("{{IMPORT}}", importPath(path)));
            case TYPESCRIPT -> Map.of("tests/" + base + ".test.ts", fill(fund ? TsTemplates.FUND_TEST : TsTemplates.WORKFLOW_TEST,
                    domain, name, pkg).replace("{{IMPORT}}", importPath(path)));
            case CSHARP -> Map.of("tests/App.Tests/" + name + "ServiceTests.cs",
                    fill(fund ? CSharpTemplates.FUND_TEST : CSharpTemplates.WORKFLOW_TEST, domain, name, pkg));
            case GO -> Map.of(dirOf(path) + base + "_test.go", fill(fund ? GoTemplates.FUND_TEST : GoTemplates.WORKFLOW_TEST,
                    domain, name, pkg).replaceFirst("package main", "package " + matchOr(GO_PACKAGE, code, "main")));
            case KOTLIN -> Map.of("src/test/kotlin/" + pkg.replace('.', '/') + "/" + name + "ServiceTest.kt",
                    fill(fund ? KotlinTemplates.FUND_TEST : KotlinTemplates.WORKFLOW_TEST, domain, name, pkg));
            default -> Map.of();
        };
    }

    private static Map<String, String> skeleton(StageLanguage language, String path, String code) {
        Set<String> names = new LinkedHashSet<>();
        Matcher m = TYPE_NAMES.matcher(code);
        while (m.find()) {
            for (int g = 1; g <= m.groupCount(); g++) {
                if (m.group(g) != null && !m.group(g).equals("main")) {
                    names.add(m.group(g));
                }
            }
        }
        String base = baseName(path);
        String pascal = pascal(base);
        StringBuilder todo = new StringBuilder();
        String comment = language == StageLanguage.JAVASCRIPT || language == StageLanguage.TYPESCRIPT
                || language == StageLanguage.CSHARP || language == StageLanguage.GO || language == StageLanguage.KOTLIN
                ? "//" : "#";
        for (String n : names) {
            todo.append(comment).append(" TODO: test ").append(n).append(": happy path, invalid input and edge cases.\n");
        }
        String header = comment + " Unit-test skeleton for " + path + " generated offline by BOT.\n" + comment
                + " Connect an AI model (Ollama or OpenAI) for behavioural tests, or complete the TODOs below.\n";
        return switch (language) {
            case JAVASCRIPT -> Map.of("tests/" + base + ".test.js", header
                    + "const subject = require('" + importPath(path) + "');\n\n"
                    + "test('module loads', () => {\n  expect(subject).toBeDefined();\n});\n" + todo);
            case TYPESCRIPT -> Map.of("tests/" + base + ".test.ts", header
                    + "import * as subject from '" + importPath(path) + "';\n\n"
                    + "test('module loads', () => {\n  expect(subject).toBeDefined();\n});\n" + todo);
            case CSHARP -> Map.of("tests/App.Tests/" + pascal + "Tests.cs", header
                    + "using Xunit;\n\nnamespace App.Tests;\n\npublic class " + pascal + "Tests\n{\n"
                    + "    [Fact(Skip = \"TODO: write behavioural tests\")]\n    public void Todo()\n    {\n    }\n}\n" + todo);
            case GO -> Map.of(dirOf(path) + base + "_test.go", header
                    + "package " + matchOr(GO_PACKAGE, code, "main") + "\n\nimport \"testing\"\n\n"
                    + "func Test" + pascal + "Todo(t *testing.T) {\n    t.Skip(\"TODO: write behavioural tests\")\n}\n" + todo);
            case KOTLIN -> {
                String pkg = matchOr(KOTLIN_PACKAGE, code, "");
                String dir = "src/test/kotlin/" + (pkg.isEmpty() ? "" : pkg.replace('.', '/') + "/");
                yield Map.of(dir + pascal + "Test.kt", header
                        + (pkg.isEmpty() ? "" : "package " + pkg + "\n\n")
                        + "import kotlin.test.Ignore\nimport kotlin.test.Test\n\nclass " + pascal + "Test {\n"
                        + "    @Ignore\n    @Test\n    fun todo() {\n    }\n}\n" + todo);
            }
            default -> Map.of();
        };
    }

    private static String fill(String template, StageDomain domain, String name, String pkg) {
        String label = domain.label().replaceAll("[\\\\$'{}]", "");
        return template
                .replace("{{NAME}}", name)
                .replace("{{PKG}}", pkg)
                .replace("{{MARKER}}", MARKER)
                .replace("{{DOMAIN}}", label)
                .replace("{{CHECKER_RULE}}", domain.checkerRule())
                .replace("{{REF_PREFIX}}", domain.refPrefix());
    }

    /** Kotlin package for the requirement, e.g. com.bank.transfer. */
    public static String kotlinPackage(StageDomain domain, String stories) {
        return StageSample.detect(stories, domain).packageName(domain, stories);
    }

    private static String importPath(String sourcePath) {
        String noExt = sourcePath.replaceAll("\\.[^./]+$", "");
        return "../" + noExt;
    }

    private static String baseName(String path) {
        String file = path.substring(path.lastIndexOf('/') + 1);
        int dot = file.lastIndexOf('.');
        return dot > 0 ? file.substring(0, dot) : file;
    }

    private static String dirOf(String path) {
        int slash = path.lastIndexOf('/');
        return slash < 0 ? "" : path.substring(0, slash + 1);
    }

    private static String pascal(String base) {
        StringBuilder sb = new StringBuilder();
        for (String part : base.split("[^A-Za-z0-9]+")) {
            if (!part.isEmpty()) {
                sb.append(Character.toUpperCase(part.charAt(0))).append(part.substring(1));
            }
        }
        String s = sb.toString();
        return s.isEmpty() || Character.isDigit(s.charAt(0)) ? "Code" + s : s;
    }

    private static String matchOr(Pattern p, String code, String fallback) {
        Matcher m = p.matcher(code);
        return m.find() ? m.group(1) : fallback;
    }
}
