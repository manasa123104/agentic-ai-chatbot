package com.agentic.chatbot.stage.template;

import com.agentic.chatbot.stage.StageDomain;
import com.agentic.chatbot.stage.StagePrompts;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Offline Python output: the submit / approve / reject workflow (same rules as the Java generic template) with a
 * pytest suite, and a pytest skeleton for any other pasted Python.
 */
public final class PythonTemplates {

    /** Marks generated code so the Tester can recognise it offline. */
    public static final String MARKER = "Generated by BOT Python workflow template";

    private static final Pattern TOP_DEF = Pattern.compile("^def\\s+([a-zA-Z]\\w*)\\s*\\(", Pattern.MULTILINE);
    private static final Pattern TOP_CLASS = Pattern.compile("^class\\s+([A-Za-z]\\w*)", Pattern.MULTILINE);

    private PythonTemplates() {
    }

    public static String module(String stories, StageDomain domain) {
        return StagePrompts.snake(StageSample.detect(stories, domain).featureName(stories));
    }

    /** app/__init__.py, app/{module}.py plus requirements.txt and pytest.ini. */
    public static Map<String, String> code(StageDomain domain, String stories) {
        String name = StageSample.detect(stories, domain).featureName(stories);
        String module = StagePrompts.snake(name);
        Map<String, String> files = new LinkedHashMap<>();
        files.put("app/__init__.py", "\"\"\"" + domain.label() + " application package generated by BOT.\"\"\"\n");
        files.put("app/" + module + ".py", fill(CODE, domain, name, module));
        return files;
    }

    /** Build files that are not shown as stage output. */
    public static Map<String, String> scaffold() {
        Map<String, String> files = new LinkedHashMap<>();
        files.put("requirements.txt", "pytest>=8.0\n");
        files.put("pytest.ini", "[pytest]\npythonpath = .\ntestpaths = tests\n");
        return files;
    }

    /** Full suite for the workflow template, else one skeleton test module per source module. */
    public static Map<String, String> tests(StageDomain domain, Map<String, String> sources) {
        Map<String, String> tests = new LinkedHashMap<>();
        for (Map.Entry<String, String> e : sources.entrySet()) {
            String code = e.getValue();
            String path = e.getKey();
            if (!path.endsWith(".py") || path.endsWith("__init__.py")) {
                continue;
            }
            String module = path.substring(0, path.length() - 3).replace('/', '.');
            String shortName = module.substring(module.lastIndexOf('.') + 1);
            Matcher service = Pattern.compile("^class\\s+(\\w+)Service\\b", Pattern.MULTILINE).matcher(code);
            if (code.contains(MARKER) && service.find()) {
                tests.put("tests/test_" + shortName + ".py", fill(TESTS, domain, service.group(1), module)
                        .replace("{{IMPORT}}", module));
            } else {
                tests.put("tests/test_" + shortName + ".py", skeleton(module, code));
            }
        }
        return tests;
    }

    private static String skeleton(String module, String code) {
        List<String> names = new ArrayList<>();
        Matcher c = TOP_CLASS.matcher(code);
        while (c.find()) {
            names.add(c.group(1));
        }
        Matcher d = TOP_DEF.matcher(code);
        while (d.find()) {
            if (!d.group(1).startsWith("_")) {
                names.add(d.group(1));
            }
        }
        StringBuilder sb = new StringBuilder();
        sb.append("\"\"\"pytest skeleton for ").append(module).append(" generated offline by BOT.\n\n")
                .append("Connect an AI model (Ollama or OpenAI) for behavioural tests, or complete the TODOs below.\n\"\"\"\n")
                .append("import importlib\n\n\n")
                .append("def test_module_imports():\n")
                .append("    assert importlib.import_module(\"").append(module).append("\") is not None\n");
        for (String n : names) {
            sb.append("\n\ndef test_").append(StagePrompts.snake(n)).append("_is_defined():\n")
                    .append("    module = importlib.import_module(\"").append(module).append("\")\n")
                    .append("    assert hasattr(module, \"").append(n).append("\")\n")
                    .append("    # TODO: test ").append(n).append(": happy path, invalid input and edge cases.\n");
        }
        return sb.toString();
    }

    private static String fill(String template, StageDomain domain, String name, String module) {
        return template
                .replace("{{NAME}}", name)
                .replace("{{MODULE}}", module)
                .replace("{{MARKER}}", MARKER)
                .replace("{{DOMAIN}}", domain.label())
                .replace("{{CHECKER_RULE}}", domain.checkerRule())
                .replace("{{REF_PREFIX}}", domain.refPrefix());
    }

    private static final String CODE = """
            \"\"\"{{NAME}} requests for the {{DOMAIN}} domain: submit, approve, reject, with an audit trail.

            {{MARKER}}.
            \"\"\"
            from __future__ import annotations

            from dataclasses import dataclass, field
            from datetime import datetime, timezone
            from enum import Enum
            from typing import Callable, Dict, List, Optional

            MAX_DETAILS = 500
            \"\"\"Business rule: request details are limited to this many characters.\"\"\"


            class {{NAME}}Status(Enum):
                \"\"\"States of a request. Only SUBMITTED requests can be decided; decisions are final.\"\"\"

                SUBMITTED = "SUBMITTED"
                APPROVED = "APPROVED"
                REJECTED = "REJECTED"


            class {{NAME}}Error(Exception):
                \"\"\"Raised when an action breaks a business rule; the message is safe to show to the user.\"\"\"


            @dataclass
            class {{NAME}}:
                \"\"\"A {{DOMAIN}} request raised by a user and decided by a reviewer.\"\"\"

                reference: str
                requested_by: str
                details: str
                created_at: datetime
                status: {{NAME}}Status = {{NAME}}Status.SUBMITTED
                decided_by: Optional[str] = None
                decision_note: Optional[str] = None


            @dataclass
            class {{NAME}}Service:
                \"\"\"Submits, approves and rejects requests and keeps an audit trail.\"\"\"

                clock: Callable[[], datetime] = lambda: datetime.now(timezone.utc)
                _requests: Dict[str, {{NAME}}] = field(default_factory=dict)
                _audit: List[str] = field(default_factory=list)
                _sequence: int = 0

                def submit(self, requested_by: str, details: str) -> {{NAME}}:
                    \"\"\"Raises a new request and returns it in status SUBMITTED.\"\"\"
                    # Business rule: every request must say who raised it and what is requested.
                    if not requested_by or not requested_by.strip():
                        raise {{NAME}}Error("Requester is required")
                    if not details or not details.strip():
                        raise {{NAME}}Error("Details are required")
                    # Business rule: details are capped to keep requests reviewable.
                    if len(details) > MAX_DETAILS:
                        raise {{NAME}}Error(f"Details must be at most {MAX_DETAILS} characters")
                    self._sequence += 1
                    reference = f"{{REF_PREFIX}}-{self._sequence:06d}"
                    request = {{NAME}}(reference, requested_by.strip(), details.strip(), self.clock())
                    self._requests[reference] = request
                    self._log(reference, "SUBMITTED", requested_by)
                    return request

                def approve(self, reference: str, reviewer: str) -> {{NAME}}:
                    \"\"\"Approves a pending request.\"\"\"
                    request = self._pending(reference)
                    self._require_reviewer(reviewer)
                    # Business rule: {{CHECKER_RULE}}.
                    if request.requested_by.lower() == reviewer.strip().lower():
                        raise {{NAME}}Error("Requester cannot approve their own request")
                    request.status = {{NAME}}Status.APPROVED
                    request.decided_by = reviewer.strip()
                    self._log(reference, "APPROVED", reviewer)
                    return request

                def reject(self, reference: str, reviewer: str, reason: str) -> {{NAME}}:
                    \"\"\"Rejects a pending request; a reason is mandatory.\"\"\"
                    request = self._pending(reference)
                    self._require_reviewer(reviewer)
                    # Business rule: a rejection must give the requester a reason.
                    if not reason or not reason.strip():
                        raise {{NAME}}Error("A reason is required to reject a request")
                    request.status = {{NAME}}Status.REJECTED
                    request.decided_by = reviewer.strip()
                    request.decision_note = reason.strip()
                    self._log(reference, "REJECTED", reviewer)
                    return request

                def find(self, reference: str) -> {{NAME}}:
                    \"\"\"Returns the request or raises if the reference is unknown.\"\"\"
                    request = self._requests.get(reference)
                    if request is None:
                        raise {{NAME}}Error(f"Request not found: {reference}")
                    return request

                def audit_trail(self) -> List[str]:
                    \"\"\"Every action taken, oldest first, as 'time reference ACTION by user'.\"\"\"
                    return list(self._audit)

                def _pending(self, reference: str) -> {{NAME}}:
                    request = self.find(reference)
                    # Business rule: decisions are final; only SUBMITTED requests can be decided.
                    if request.status is not {{NAME}}Status.SUBMITTED:
                        raise {{NAME}}Error(f"Request {reference} is already {request.status.value}")
                    return request

                @staticmethod
                def _require_reviewer(reviewer: str) -> None:
                    if not reviewer or not reviewer.strip():
                        raise {{NAME}}Error("Reviewer is required")

                def _log(self, reference: str, action: str, user: str) -> None:
                    # Business rule: every action is recorded with who did it and when.
                    self._audit.append(f"{self.clock().isoformat()} {reference} {action} by {user}")


            if __name__ == "__main__":
                service = {{NAME}}Service()
                created = service.submit("alice", "Example {{DOMAIN}} request")
                print(f"Created {created.reference} with status {created.status.value}")
            """;

    private static final String TESTS = """
            \"\"\"pytest suite for {{IMPORT}} ({{DOMAIN}}).\"\"\"
            from datetime import datetime, timezone

            import pytest

            from {{IMPORT}} import MAX_DETAILS, {{NAME}}Error, {{NAME}}Service, {{NAME}}Status

            FIXED = datetime(2026, 1, 1, tzinfo=timezone.utc)


            @pytest.fixture
            def service():
                return {{NAME}}Service(clock=lambda: FIXED)


            def test_submit_creates_submitted_request_with_reference(service):
                # Proves a valid request is saved with status SUBMITTED and a reference number.
                request = service.submit("alice", "Need approval")
                assert request.status is {{NAME}}Status.SUBMITTED
                assert request.reference == "{{REF_PREFIX}}-000001"
                assert service.find(request.reference) is request


            @pytest.mark.parametrize("who, details, message", [
                ("", "x", "Requester is required"),
                ("alice", "  ", "Details are required"),
                ("alice", "x" * (MAX_DETAILS + 1), "at most"),
            ])
            def test_submit_validates_input(service, who, details, message):
                # Proves invalid submissions are rejected with a clear message.
                with pytest.raises({{NAME}}Error, match=message):
                    service.submit(who, details)


            def test_reviewer_can_approve(service):
                request = service.submit("alice", "Need approval")
                approved = service.approve(request.reference, "bob")
                assert approved.status is {{NAME}}Status.APPROVED
                assert approved.decided_by == "bob"


            def test_requester_cannot_approve_own_request(service):
                # Proves the four-eyes rule.
                request = service.submit("alice", "Need approval")
                with pytest.raises({{NAME}}Error, match="cannot approve their own request"):
                    service.approve(request.reference, "ALICE")


            def test_reject_needs_a_reason(service):
                request = service.submit("alice", "Need approval")
                with pytest.raises({{NAME}}Error, match="reason is required"):
                    service.reject(request.reference, "bob", " ")
                rejected = service.reject(request.reference, "bob", "Missing documents")
                assert rejected.status is {{NAME}}Status.REJECTED
                assert rejected.decision_note == "Missing documents"


            def test_decisions_are_final(service):
                request = service.submit("alice", "Need approval")
                service.approve(request.reference, "bob")
                with pytest.raises({{NAME}}Error, match="already APPROVED"):
                    service.reject(request.reference, "carol", "Too late")


            def test_unknown_reference_is_reported(service):
                with pytest.raises({{NAME}}Error, match="Request not found"):
                    service.find("NOPE")


            def test_audit_trail_records_every_action(service):
                request = service.submit("alice", "Need approval")
                service.approve(request.reference, "bob")
                trail = service.audit_trail()
                assert len(trail) == 2
                assert "SUBMITTED by alice" in trail[0]
                assert "APPROVED by bob" in trail[1]
            """;
}
