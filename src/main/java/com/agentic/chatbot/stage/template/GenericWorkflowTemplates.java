package com.agentic.chatbot.stage.template;

import com.agentic.chatbot.stage.StageDomain;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Offline fallback for requirements without a dedicated sample: a submit / approve / reject workflow with an
 * audit trail, named after the feature (e.g. LoanApplication). Banking gets a maker-checker rule wording,
 * logistics a dispatcher sign-off wording; the code is the same.
 */
final class GenericWorkflowTemplates {

    /** Marks generated code so the unit tester can recognise it and produce matching tests offline. */
    static final String MARKER = "Generated by BOT workflow template";

    private GenericWorkflowTemplates() {
    }

    static Map<String, String> code(StageDomain domain, String pkg, String name) {
        String dir = "src/main/java/" + pkg.replace('.', '/') + "/";
        Map<String, String> files = new LinkedHashMap<>();
        files.put(dir + name + "Status.java", fill(STATUS, domain, pkg, name));
        files.put(dir + name + ".java", fill(ENTITY, domain, pkg, name));
        files.put(dir + name + "Exception.java", fill(EXCEPTION, domain, pkg, name));
        files.put(dir + name + "Service.java", fill(SERVICE, domain, pkg, name));
        return files;
    }

    static Map<String, String> tests(StageDomain domain, String pkg, String name) {
        String dir = "src/test/java/" + pkg.replace('.', '/') + "/";
        return Map.of(dir + name + "ServiceTest.java", fill(SERVICE_TEST, domain, pkg, name));
    }

    private static String fill(String template, StageDomain domain, String pkg, String name) {
        String var = Character.toLowerCase(name.charAt(0)) + name.substring(1);
        return template
                .replace("{{PKG}}", pkg)
                .replace("{{NAME}}", name)
                .replace("{{VAR}}", var)
                .replace("{{MARKER}}", MARKER)
                .replace("{{DOMAIN}}", domain.label())
                .replace("{{CHECKER_RULE}}", domain.checkerRule())
                .replace("{{REF_PREFIX}}", domain.refPrefix());
    }

    private static final String STATUS = """
            package {{PKG}};

            /**
             * States of a {@link {{NAME}}}. Only SUBMITTED requests can be decided; decisions are final.
             * {{MARKER}} ({{DOMAIN}}).
             */
            public enum {{NAME}}Status {
                SUBMITTED, APPROVED, REJECTED
            }
            """;

    private static final String ENTITY = """
            package {{PKG}};

            import java.time.Instant;

            /**
             * A {{DOMAIN}} request raised by a user and decided by a reviewer.
             * {{MARKER}}.
             */
            public class {{NAME}} {

                private final String reference;
                private final String requestedBy;
                private final String details;
                private final Instant createdAt;
                private {{NAME}}Status status = {{NAME}}Status.SUBMITTED;
                private String decidedBy;
                private String decisionNote;

                /**
                 * @param reference   unique reference number
                 * @param requestedBy user who raised the request
                 * @param details     what is being requested
                 * @param createdAt   when it was raised
                 */
                public {{NAME}}(String reference, String requestedBy, String details, Instant createdAt) {
                    this.reference = reference;
                    this.requestedBy = requestedBy;
                    this.details = details;
                    this.createdAt = createdAt;
                }

                /** @return unique reference number */
                public String getReference() {
                    return reference;
                }

                /** @return user who raised the request */
                public String getRequestedBy() {
                    return requestedBy;
                }

                /** @return what is being requested */
                public String getDetails() {
                    return details;
                }

                /** @return when the request was raised */
                public Instant getCreatedAt() {
                    return createdAt;
                }

                /** @return current state */
                public {{NAME}}Status getStatus() {
                    return status;
                }

                /** @return reviewer who decided, or null while pending */
                public String getDecidedBy() {
                    return decidedBy;
                }

                /** @return reason given with the decision, or null */
                public String getDecisionNote() {
                    return decisionNote;
                }

                void decide({{NAME}}Status newStatus, String reviewer, String note) {
                    this.status = newStatus;
                    this.decidedBy = reviewer;
                    this.decisionNote = note;
                }
            }
            """;

    private static final String EXCEPTION = """
            package {{PKG}};

            /**
             * Raised when a {@link {{NAME}}} action breaks a business rule.
             */
            public class {{NAME}}Exception extends RuntimeException {

                /** @param message message safe to show to the user */
                public {{NAME}}Exception(String message) {
                    super(message);
                }
            }
            """;

    private static final String SERVICE = """
            package {{PKG}};

            import java.time.Clock;
            import java.time.Instant;
            import java.util.ArrayList;
            import java.util.LinkedHashMap;
            import java.util.List;
            import java.util.Map;

            /**
             * Submits, approves and rejects {@link {{NAME}}} requests and keeps an audit trail.
             * {{MARKER}} ({{DOMAIN}}).
             */
            public class {{NAME}}Service {

                /** Business rule: request details are limited to this many characters. */
                public static final int MAX_DETAILS = 500;

                private final Map<String, {{NAME}}> requests = new LinkedHashMap<>();
                private final List<String> auditTrail = new ArrayList<>();
                private final Clock clock;
                private long sequence;

                /** @param clock time source; inject a fixed clock in tests */
                public {{NAME}}Service(Clock clock) {
                    this.clock = clock;
                }

                /** Uses the UTC system clock. */
                public {{NAME}}Service() {
                    this(Clock.systemUTC());
                }

                /**
                 * Raises a new request.
                 *
                 * @param requestedBy user raising it
                 * @param details     what is requested
                 * @return the request in status SUBMITTED
                 */
                public synchronized {{NAME}} submit(String requestedBy, String details) {
                    // Business rule: every request must say who raised it and what is requested.
                    if (requestedBy == null || requestedBy.isBlank()) {
                        throw new {{NAME}}Exception("Requester is required");
                    }
                    if (details == null || details.isBlank()) {
                        throw new {{NAME}}Exception("Details are required");
                    }
                    // Business rule: details are capped to keep requests reviewable.
                    if (details.length() > MAX_DETAILS) {
                        throw new {{NAME}}Exception("Details must be at most " + MAX_DETAILS + " characters");
                    }
                    String reference = "{{REF_PREFIX}}-" + String.format("%06d", ++sequence);
                    {{NAME}} {{VAR}} = new {{NAME}}(reference, requestedBy.trim(), details.trim(), Instant.now(clock));
                    requests.put(reference, {{VAR}});
                    audit(reference, "SUBMITTED", requestedBy);
                    return {{VAR}};
                }

                /**
                 * Approves a pending request.
                 *
                 * @param reference request to approve
                 * @param reviewer  user approving it
                 * @return the approved request
                 */
                public synchronized {{NAME}} approve(String reference, String reviewer) {
                    {{NAME}} {{VAR}} = pending(reference);
                    requireReviewer(reviewer);
                    // Business rule: {{CHECKER_RULE}}.
                    if ({{VAR}}.getRequestedBy().equalsIgnoreCase(reviewer.trim())) {
                        throw new {{NAME}}Exception("Requester cannot approve their own request");
                    }
                    {{VAR}}.decide({{NAME}}Status.APPROVED, reviewer.trim(), null);
                    audit(reference, "APPROVED", reviewer);
                    return {{VAR}};
                }

                /**
                 * Rejects a pending request.
                 *
                 * @param reference request to reject
                 * @param reviewer  user rejecting it
                 * @param reason    why it is rejected
                 * @return the rejected request
                 */
                public synchronized {{NAME}} reject(String reference, String reviewer, String reason) {
                    {{NAME}} {{VAR}} = pending(reference);
                    requireReviewer(reviewer);
                    // Business rule: a rejection must give the requester a reason.
                    if (reason == null || reason.isBlank()) {
                        throw new {{NAME}}Exception("A reason is required to reject a request");
                    }
                    {{VAR}}.decide({{NAME}}Status.REJECTED, reviewer.trim(), reason.trim());
                    audit(reference, "REJECTED", reviewer);
                    return {{VAR}};
                }

                /**
                 * @param reference request reference
                 * @return the request
                 */
                public synchronized {{NAME}} find(String reference) {
                    {{NAME}} {{VAR}} = requests.get(reference);
                    if ({{VAR}} == null) {
                        throw new {{NAME}}Exception("Request not found: " + reference);
                    }
                    return {{VAR}};
                }

                /** @return every action taken, oldest first, as "time reference ACTION by user" */
                public synchronized List<String> auditTrail() {
                    return List.copyOf(auditTrail);
                }

                private {{NAME}} pending(String reference) {
                    {{NAME}} {{VAR}} = find(reference);
                    // Business rule: decisions are final; only SUBMITTED requests can be decided.
                    if ({{VAR}}.getStatus() != {{NAME}}Status.SUBMITTED) {
                        throw new {{NAME}}Exception("Request " + reference + " is already " + {{VAR}}.getStatus());
                    }
                    return {{VAR}};
                }

                private static void requireReviewer(String reviewer) {
                    if (reviewer == null || reviewer.isBlank()) {
                        throw new {{NAME}}Exception("Reviewer is required");
                    }
                }

                private void audit(String reference, String action, String user) {
                    // Business rule: every action is recorded with who did it and when.
                    auditTrail.add(Instant.now(clock) + " " + reference + " " + action + " by " + user);
                }
            }
            """;

    private static final String SERVICE_TEST = """
            package {{PKG}};

            import org.junit.jupiter.api.BeforeEach;
            import org.junit.jupiter.api.Test;

            import java.time.Clock;
            import java.time.Instant;
            import java.time.ZoneOffset;

            import static org.junit.jupiter.api.Assertions.assertEquals;
            import static org.junit.jupiter.api.Assertions.assertThrows;
            import static org.junit.jupiter.api.Assertions.assertTrue;

            /**
             * Unit tests for {@link {{NAME}}Service}.
             */
            class {{NAME}}ServiceTest {

                private {{NAME}}Service service;

                @BeforeEach
                void setUp() {
                    service = new {{NAME}}Service(Clock.fixed(Instant.parse("2026-01-15T10:00:00Z"), ZoneOffset.UTC));
                }

                @Test
                void submitCreatesSubmittedRequestWithReference() {
                    {{NAME}} {{VAR}} = service.submit("alice", "Please process this request");
                    assertEquals({{NAME}}Status.SUBMITTED, {{VAR}}.getStatus());
                    assertTrue({{VAR}}.getReference().startsWith("{{REF_PREFIX}}-"));
                }

                @Test
                void submitWithoutDetailsIsRejected() {
                    {{NAME}}Exception e = assertThrows({{NAME}}Exception.class, () -> service.submit("alice", " "));
                    assertEquals("Details are required", e.getMessage());
                }

                @Test
                void anotherUserCanApprove() {
                    String ref = service.submit("alice", "Request").getReference();
                    {{NAME}} approved = service.approve(ref, "bob");
                    assertEquals({{NAME}}Status.APPROVED, approved.getStatus());
                    assertEquals("bob", approved.getDecidedBy());
                }

                @Test
                void requesterCannotApproveOwnRequest() {
                    String ref = service.submit("alice", "Request").getReference();
                    {{NAME}}Exception e = assertThrows({{NAME}}Exception.class, () -> service.approve(ref, "Alice"));
                    assertEquals("Requester cannot approve their own request", e.getMessage());
                }

                @Test
                void rejectNeedsReasonAndDecisionsAreFinal() {
                    String ref = service.submit("alice", "Request").getReference();
                    assertThrows({{NAME}}Exception.class, () -> service.reject(ref, "bob", ""));
                    service.reject(ref, "bob", "Missing documents");
                    assertThrows({{NAME}}Exception.class, () -> service.approve(ref, "carol"));
                }

                @Test
                void everyActionIsAudited() {
                    String ref = service.submit("alice", "Request").getReference();
                    service.approve(ref, "bob");
                    assertEquals(2, service.auditTrail().size());
                    assertTrue(service.auditTrail().get(1).contains("APPROVED by bob"));
                }
            }
            """;
}
