package com.agentic.chatbot.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.stream.Stream;

/**
 * Collects the generated website into a folder that can be pushed to GitHub: the generated project (templates, Java or
 * server code, SITE_* files, uploaded images) plus a plain {@code site/} folder of static HTML pages with relative
 * links, so the website also opens straight from the repository or from GitHub Pages.
 */
@Service
public class SiteExportService {

    private static final Set<String> SKIP_DIRS = Set.of("target", "node_modules", ".git", "conversions", ".runs");

    private final SiteStyleService styles;
    private final ObjectMapper mapper = new ObjectMapper();

    public SiteExportService(SiteStyleService styles) {
        this.styles = styles;
    }

    public Path siteDir() {
        return styles.outputDir();
    }

    /** True when a generated website (at least one HTML template) exists. */
    public boolean hasSite() {
        return hasSite(siteDir());
    }

    public static boolean hasSite(Path siteDir) {
        Path templates = siteDir.resolve("src/main/resources/templates");
        if (!Files.isDirectory(templates)) {
            return false;
        }
        try (Stream<Path> files = Files.list(templates)) {
            return files.anyMatch(p -> p.getFileName().toString().endsWith(".html"));
        } catch (IOException e) {
            return false;
        }
    }

    /** The business name recorded for the site, or "site". */
    public String brand() {
        return brand(siteDir());
    }

    public static String brand(Path siteDir) {
        try {
            Path meta = siteDir.resolve("SITE_META.json");
            if (Files.exists(meta)) {
                JsonNode node = new ObjectMapper().readTree(Files.readString(meta, StandardCharsets.UTF_8));
                JsonNode b = node.get("brand");
                if (b != null && !b.asText().isBlank()) {
                    return b.asText();
                }
            }
        } catch (IOException ignored) {
            // fall through
        }
        return "site";
    }

    /** A lowercase, URL-safe version of the brand for branch names. */
    public static String slug(String text) {
        String s = text == null ? "" : text.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9]+", "-").replaceAll("^-+|-+$", "");
        return s.isEmpty() ? "site" : s;
    }

    /** Copies the generated website into {@code target}; returns the number of files written. */
    public int export(Path target) throws IOException {
        return export(siteDir(), target);
    }

    public static int export(Path siteDir, Path target) throws IOException {
        if (!hasSite(siteDir)) {
            throw new IllegalArgumentException("There is no generated website yet. Describe a website to BOT first, then push it.");
        }
        Files.createDirectories(target);
        int[] count = {0};
        try (Stream<Path> walk = Files.walk(siteDir)) {
            for (Path p : (Iterable<Path>) walk::iterator) {
                if (!Files.isRegularFile(p)) {
                    continue;
                }
                Path rel = siteDir.relativize(p);
                if (skipped(rel)) {
                    continue;
                }
                Path dest = target.resolve(rel.toString());
                Files.createDirectories(dest.getParent());
                Files.copy(p, dest, java.nio.file.StandardCopyOption.REPLACE_EXISTING);
                count[0]++;
            }
        }
        count[0] += writeStaticPages(siteDir, target);
        if (!Files.exists(target.resolve("README.md"))) {
            String brand = brand(siteDir);
            Files.writeString(target.resolve("README.md"), "# " + brand + "\n\n"
                    + "Website generated by BOT.\n\n"
                    + "- `site/index.html` - the pages as plain HTML; open it in a browser or serve the `site/` folder "
                    + "(for example with GitHub Pages).\n"
                    + "- `src/main/resources/templates/` - the Thymeleaf templates of the Spring Boot project.\n"
                    + "- `USER_STORY.md`, `SITE_META.json`, `SITE_STYLE.json` - the story and settings behind the site.\n",
                    StandardCharsets.UTF_8);
            count[0]++;
        }
        return count[0];
    }

    private static boolean skipped(Path rel) {
        for (Path part : rel) {
            if (SKIP_DIRS.contains(part.toString())) {
                return true;
            }
        }
        return rel.getFileName().toString().equals(".gitkeep");
    }

    /** Writes site/&lt;page&gt;.html for every template with relative links; site/index.html is the home page. */
    private static int writeStaticPages(Path siteDir, Path target) throws IOException {
        Path templates = siteDir.resolve("src/main/resources/templates");
        Path out = target.resolve("site");
        Files.createDirectories(out);
        int written = 0;
        List<Path> pages;
        try (Stream<Path> files = Files.list(templates)) {
            pages = files.filter(p -> p.getFileName().toString().endsWith(".html")).sorted().toList();
        }
        for (Path page : pages) {
            String name = page.getFileName().toString();
            String html = staticHtml(Files.readString(page, StandardCharsets.UTF_8));
            Files.writeString(out.resolve(name), html, StandardCharsets.UTF_8);
            written++;
            if (name.equals("home.html")) {
                Files.writeString(out.resolve("index.html"), html, StandardCharsets.UTF_8);
                written++;
            }
        }
        return written;
    }

    /** Turns a template into a standalone page: no Thymeleaf attributes, /site/x links become x.html. */
    static String staticHtml(String template) {
        String html = template
                .replaceAll("\\sxmlns:th=\"[^\"]*\"", "")
                .replaceAll("\\sth:[a-zA-Z]+=\"[^\"]*\"", "")
                .replaceAll("(?s)<div><strong>Tools</strong>.*?</div>", "")
                .replace("action=\"/site/contact\"", "action=\"contact-success.html\"")
                .replaceAll("(href|action)=\"/site/([A-Za-z0-9-]+)\"", "$1=\"$2.html\"")
                .replace("href=\"/\"", "href=\"index.html\"")
                .replaceAll("method=\"post\"", "method=\"get\"");
        return html;
    }
}
